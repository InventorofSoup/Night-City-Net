const storyDialog = document.querySelector("#story-dialog");
const storyContent = document.querySelector("#story-content");
const tipDialog = document.querySelector("#tip-dialog");
const toast = document.querySelector("#toast");
let toastTimer;

function showToast(message) {
  toast.textContent = message;
  toast.classList.add("show");
  window.clearTimeout(toastTimer);
  toastTimer = window.setTimeout(() => toast.classList.remove("show"), 3400);
}

function openStory(id) {
  const story = stories[id];
  if (!story) {
    showToast("STORY FILE MOVED, DELETED, OR NEVER EXISTED.");
    return;
  }
  const paragraphs = story.body.map((paragraph) => `<p>${paragraph}</p>`).join("");
  const comments = story.comments.map((comment) => `
    <div class="comment">
      <b>@${comment[0]}</b>
      <p>${comment[1]}</p>
      <button type="button" data-comment-reply="${comment[2]}">REPLY // ${comment[2]}</button>
    </div>
  `).join("");
  storyContent.innerHTML = `
    <span class="story-label">${story.label}</span>
    <h2>${story.title}</h2>
    <p class="dek">${story.dek}</p>
    <p class="story-meta">${story.meta}</p>
    <div class="story-body">${paragraphs}</div>
    <section class="comments">
      <h3>THE COMMENTS HAVE ESCALATED</h3>
      ${comments}
    </section>
  `;
  storyContent.querySelectorAll("[data-comment-reply]").forEach((button) => {
    button.addEventListener("click", () => showToast(button.dataset.commentReply));
  });
  storyDialog.showModal();
}

document.querySelectorAll("[data-story]").forEach((button) => {
  button.addEventListener("click", () => openStory(button.dataset.story));
});

document.querySelectorAll("[data-close-dialog]").forEach((button) => {
  button.addEventListener("click", () => button.closest("dialog").close());
});

[storyDialog, tipDialog].forEach((dialog) => {
  dialog.addEventListener("click", (event) => {
    if (event.target === dialog) dialog.close();
  });
});

document.querySelectorAll("[data-reactions]").forEach((group) => {
  group.querySelectorAll("button").forEach((button) => {
    button.addEventListener("click", () => {
      group.querySelectorAll("button").forEach((item) => item.classList.remove("selected"));
      button.classList.add("selected");
      const count = button.querySelector("b");
      count.textContent = Number(count.textContent.replace(/,/g, "")) + 1;
      showToast("REACTION RECORDED. YOUR FEED IS NOW SLIGHTLY WORSE.");
    });
  });
});

const filterButtons = document.querySelectorAll("[data-filter]");
const feedItems = document.querySelectorAll("[data-feed-item]");
const filterStatus = document.querySelector("#filter-status");

filterButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const filter = button.dataset.filter;
    filterButtons.forEach((item) => item.classList.toggle("active", item === button));
    feedItems.forEach((item) => {
      const categories = (item.dataset.category || "").split(" ");
      item.classList.toggle("filtered-out", filter !== "all" && !categories.includes(filter));
    });
    filterStatus.textContent = filter === "all"
      ? "showing everything, unfortunately"
      : `filter stuck on ${button.textContent.toLowerCase()}`;
    document.querySelector(".mess-grid").scrollIntoView({ block: "start" });
  });
});

document.querySelector("#search-form").addEventListener("submit", (event) => {
  event.preventDefault();
  const query = document.querySelector("#site-search").value.trim().toLowerCase();
  if (!query) {
    showToast("TYPE SOMETHING FIRST. WE CANNOT MISINTERPRET SILENCE.");
    return;
  }
  const match = Object.entries(stories).find(([, story]) =>
    [story.title, story.dek, story.label, ...story.body].join(" ").toLowerCase().includes(query)
  );
  if (match) openStory(match[0]);
  else showToast(`NO RESULTS FOR “${query.toUpperCase()}.” TRY A LESS ACCURATE WORD.`);
});

const rumorRange = document.querySelector("#rumor-range");
const rumorOutput = document.querySelector("#rumor-output");
const rumorLabels = [
  [15, "OBVIOUSLY MADE UP"],
  [35, "PROBABLY A JOKE"],
  [55, "WORTH ARGUING ABOUT"],
  [75, "REPEATABLE AT PARTIES"],
  [90, "BASICALLY CONFIRMED"],
  [101, "MORE TRUE THAN TRUTH"],
];
rumorRange.addEventListener("input", () => {
  const value = Number(rumorRange.value);
  const label = rumorLabels.find(([limit]) => value < limit)[1];
  rumorOutput.textContent = `${value}% // ${label}`;
});

