function randomInt(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

function shuffled(items) {
  const copy = [...items];
  for (let index = copy.length - 1; index > 0; index -= 1) {
    const target = randomInt(0, index);
    [copy[index], copy[target]] = [copy[target], copy[index]];
  }
  return copy;
}

function pickComments(story) {
  const count = randomInt(2, 7);
  const specific = shuffled(story.comments).slice(0, Math.min(2, count));
  const general = shuffled(communityComments).slice(0, count - specific.length);
  return shuffled(specific.concat(general));
}

const storyDialog = document.querySelector("#story-dialog");
const storyContent = document.querySelector("#story-content");
const tipDialog = document.querySelector("#tip-dialog");
const toast = document.querySelector("#toast");
let toastTimer;

function showToast(message) {
  toast.textContent = message;
  toast.classList.add("show");
  window.clearTimeout(toastTimer);
  toastTimer = window.setTimeout(() => toast.classList.remove("show"), 3400);
}

function openStory(id) {
  const story = stories[id];
  if (!story) {
    showToast("STORY FILE MOVED, DELETED, OR NEVER EXISTED.");
    return;
  }
  const paragraphs = story.body.concat(additionalReporting[id] || [])
    .map((paragraph) => `<p>${paragraph}</p>`).join("");
  const visibleComments = pickComments(story);
  const claimedTotal = randomInt(Math.max(visibleComments.length + 20, 80), 4800);
  const comments = visibleComments.map((comment) => `
    <div class="comment">
      <b>@${comment[0]}</b>
      <p>${comment[1]}</p>
      <button type="button" data-comment-reply="${comment[2]}">REPLY // ${comment[2]}</button>
    </div>
  `).join("");
  storyContent.innerHTML = `
    <span class="story-label">${story.label}</span>
    <h2>${story.title}</h2>
    <p class="dek">${story.dek}</p>
    <p class="story-meta">${story.meta}</p>
    <div class="story-body">${paragraphs}</div>
    <section class="comments">
      <h3>THE COMMENTS HAVE ESCALATED</h3>
      <p class="comment-count">SHOWING ${visibleComments.length} OF ${claimedTotal.toLocaleString()} CLAIMED COMMENTS // REFRESH FOR A DIFFERENT ARGUMENT</p>
      ${comments}
    </section>
  `;
  storyContent.querySelectorAll("[data-comment-reply]").forEach((button) => {
    button.addEventListener("click", () => showToast(button.dataset.commentReply));
  });
  storyDialog.showModal();
}

